// scripts/gen-locale-types.mjs
// Regenerates src/locales/keys.d.ts from en.json. Run it after adding keys:
//   npm run i18n:types
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { leaves } from '../src/locale-keys.js';

const here = dirname(fileURLToPath(import.meta.url));
const en = JSON.parse(readFileSync(resolve(here, '../src/locales/en.json'), 'utf8'));

const union = leaves(en).sort().map((k) => `  | ${JSON.stringify(k)}`).join('\n');

writeFileSync(
  resolve(here, '../src/locales/keys.d.ts'),
  `// GENERATED by scripts/gen-locale-types.mjs — do not edit.\n` +
    `// Run \`npm run i18n:types\` after changing en.json.\n` +
    `export type LocaleKey =\n${union};\n`,
);

console.log(`wrote keys.d.ts — ${leaves(en).length} keys`);
